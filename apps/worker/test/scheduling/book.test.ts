const MONEY_TEXT = /\$|\bsalary\b|\bcompensation\b|\bequity\b|\bpay\b/i;

/** Offers three slots and has the user confirm the n-th link. */
async function offerAndConfirm(s: Seeded, h: Harness, n = 0, compensation = false) {
  const out = await offerSlots(s.t.handle, offerInput(s, threeSlots(), compensation), h.deps);
  const request = h.sender.sent.filter((m) => m.kind === 'slot_confirmation').at(-1)!;
  const confirmed = await confirmToken(s.t.handle, tokensIn(request)[n]!);
  expect(confirmed.ok).toBe(true);
  return out.interviewId!;
}

const replies = (h: Harness) => h.sender.sent.filter((m) => m.kind === 'recruiter_reply');
const book = (s: Seeded, h: Harness, interviewId: string) =>
  bookInterview(s.t.handle, { userId: s.t.userId, interviewId }, h.deps);

describe('bookInterview (rule 10, task 5.5)', () => {
  it('replies on the recruiter thread, creates the event, stores its id, sets Interviewing and logs', async () => {
    const s = await seedThread(env);
    const h = makeHarness();
    const interviewId = await offerAndConfirm(s, h, 1);
    expect(replies(h)).toHaveLength(0);

    const out = await book(s, h, interviewId);
    expect(out).toMatchObject({
      status: 'booked',
      eventId: expect.stringMatching(/^[0-9a-f]{32}$/),
      created: true,
    });

    expect(replies(h)).toHaveLength(1);
    const reply = replies(h)[0]!;
    expect(reply.to).toBe('recruiter@acme.example');
    expect(reply.threadId).toBe(s.thread.gmailThreadId);
    expect(reply.inReplyTo).toBe('<msg-1@acme.example>');
    expect(reply.text).toContain('Friday, November 13, 2037, 10:00 AM to 11:00 AM PST');
    expect(reply.text).toContain('Hello Dana Recruiter,');
    expect(reply.text).toContain('Mara Quill');

    expect(h.calendar.created).toHaveLength(1);
    const event = h.calendar.created[0]!;
    expect(event.summary).toBe(`Interview: Staff Engineer at ${s.companyName}`);
    expect(event.description).toContain('Interviewer: Dana Recruiter');
    expect(event.start.toISOString()).toBe('2037-11-13T18:00:00.000Z');
    expect(event.end.toISOString()).toBe('2037-11-13T19:00:00.000Z');
    expect(event.timeZone).toBe('America/Los_Angeles');

    const row = (await getInterview(s.t.handle, interviewId))!;
    // The id was generated by us and persisted before the insert.
    expect(row.calendarEventId).toBe((out as { eventId: string }).eventId);
    expect(row.calendarEventClientId).toBe(row.calendarEventId);
    expect(h.calendar.created[0]!.id).toBe(row.calendarEventId);
    expect(row.bookedGeneration).toBe(row.confirmedGeneration);
    expect(row.replySentAt).not.toBeNull();
    expect((await getApplication(s.t.handle, s.application.id))?.status).toBe('interviewing');
    expect(h.reminders).toEqual([interviewId]);

    const actions = (await activity.listByUser(s.t.handle, s.t.userId)).map((e) => e.action);
    expect(actions).toEqual(
      expect.arrayContaining(['interview_reply_sent', 'interview_booked', 'status_changed']),
    );
  });

  it('does nothing for an interview the user has not confirmed', async () => {
    const s = await seedThread(env);
    const h = makeHarness();
    const out = await offerSlots(s.t.handle, offerInput(s, threeSlots()), h.deps);
    expect(await book(s, h, out.interviewId!)).toEqual({ status: 'not_confirmed' });
    expect(replies(h)).toHaveLength(0);
    expect(h.calendar.created).toHaveLength(0);
    expect(h.mailbox.calls).toBe(0);
    expect((await getApplication(s.t.handle, s.application.id))?.status).toBe('applied');
  });

  it('an event failure after the reply retries the event only and never re-sends the reply', async () => {
    const s = await seedThread(env);
    const h = makeHarness();
    const interviewId = await offerAndConfirm(s, h);
    h.calendar.failCreates = 1;

    await expect(book(s, h, interviewId)).rejects.toBeInstanceOf(EventCreationError);
    expect(replies(h)).toHaveLength(1);
    let row = (await getInterview(s.t.handle, interviewId))!;
    expect(row.replySentAt).not.toBeNull();
    expect(row.calendarEventId).toBeNull();
    expect(row.confirmedSlotId).not.toBeNull();
    const failed = (await activity.listByUser(s.t.handle, s.t.userId)).filter(
      (e) => e.action === 'interview_event_failed',
    );
    expect(failed).toHaveLength(1);

    const retry = await book(s, h, interviewId);
    expect(retry).toMatchObject({ status: 'booked', created: true });
    expect(replies(h)).toHaveLength(1);
    expect(h.store.rows.filter((r) => r.kind === 'recruiter_reply')).toHaveLength(1);
    expect(h.calendar.created).toHaveLength(1);
    row = (await getInterview(s.t.handle, interviewId))!;
    expect(row.calendarEventId).toBe(h.calendar.created[0]!.id);
    expect((await getApplication(s.t.handle, s.application.id))?.status).toBe('interviewing');
  });

  it('a second run after success sends no second reply and creates no second event', async () => {
    const s = await seedThread(env);
    const h = makeHarness();
    const interviewId = await offerAndConfirm(s, h);
    await book(s, h, interviewId);
    const again = await book(s, h, interviewId);
    expect(again).toMatchObject({ status: 'booked', created: false });
    expect(replies(h)).toHaveLength(1);
    expect(h.calendar.created).toHaveLength(1);
  });

  it('a blocked reply is not recorded as sent and creates no event', async () => {
    const s = await seedThread(env);
    const h = makeHarness();
    const interviewId = await offerAndConfirm(s, h);
    const blockAll: ContentGuard = {
      name: 'test',
      check: () => ({ ok: false, reason: 'blocked' }),
    };
    h.setGuards([blockAll]);
    expect(await book(s, h, interviewId)).toEqual({ status: 'reply_blocked' });
    expect((await getInterview(s.t.handle, interviewId))?.replySentAt).toBeNull();
    expect(h.calendar.created).toHaveLength(0);
  });
});

describe('reschedule (rule 11, task 5.6)', () => {
  it('new times on a confirmed interview create new slots and a new request and leave the event alone until confirmed', async () => {
    const s = await seedThread(env);
    const h = makeHarness();
    const interviewId = await offerAndConfirm(s, h, 0);
    await book(s, h, interviewId);
    const sentBefore = h.sender.sent.length;
    expect(replies(h)).toHaveLength(1);

    const out = await offerSlots(
      s.t.handle,
      {
        ...offerInput(s, [
          proposed('2037-11-17T09:00:00-08:00'),
          proposed('2037-11-18T09:00:00-08:00'),
        ]),
        messageId: 'gmail-msg-2',
        reschedule: true,
      },
      h.deps,
    );
    expect(out).toMatchObject({ status: 'offered', reschedule: true, offered: 2, interviewId });

    // A new confirmation request to the user, no reply to the recruiter.
    expect(h.sender.sent.length).toBe(sentBefore + 1);
    const request = h.sender.sent.at(-1)!;
    expect(request.kind).toBe('slot_confirmation');
    expect(request.to).toBe(s.t.email);
    expect(replies(h)).toHaveLength(1);

    // The event is untouched and still linked; the interview waits for a new confirmation.
    expect(h.calendar.created).toHaveLength(1);
    expect(h.calendar.updated).toHaveLength(0);
    let row = (await getInterview(s.t.handle, interviewId))!;
    const eventId = h.calendar.created[0]!.id;
    expect(row.calendarEventId).toBe(eventId);
    expect(row.confirmedSlotId).toBeNull();
    expect(row.confirmedAt).toBeNull();
    const slots = await listSlotsForInterview(s.t.handle, interviewId);
    expect(slots.filter((r) => !r.invalidatedAt && !r.confirmedAt)).toHaveLength(2);

    // Booking before the user confirms does nothing.
    expect(await book(s, h, interviewId)).toEqual({ status: 'not_confirmed' });
    expect(h.calendar.updated).toHaveLength(0);

    // Confirming a new slot replies once more and updates the same event (no duplicate).
    expect((await confirmToken(s.t.handle, tokensIn(request)[1]!)).ok).toBe(true);
    const booked = await book(s, h, interviewId);
    expect(booked).toMatchObject({ status: 'booked', eventId, created: false });
    expect(h.calendar.created).toHaveLength(1);
    expect(h.calendar.updated).toHaveLength(1);
    expect(h.calendar.updated[0]!.id).toBe(eventId);
    expect(h.calendar.updated[0]!.start.toISOString()).toBe('2037-11-18T17:00:00.000Z');
    expect(replies(h)).toHaveLength(2);
    expect(replies(h)[1]!.text).toContain('Wednesday, November 18, 2037, 9:00 AM');
    row = (await getInterview(s.t.handle, interviewId))!;
    expect(row.calendarEventId).toBe(eventId);
    expect(row.bookedGeneration).toBe(row.confirmedGeneration);
    expect(h.reminders).toEqual([interviewId, interviewId]);
  });
});

describe('never discussed or followed (rule 6 and 7, task 5.7)', () => {
  it('a booking-link thread produces no slots, no email, no reply and no calendar call', async () => {
    const s = await seedThread(env);
    const h = makeHarness();
    const out = await offerSlots(s.t.handle, offerInput(s, [], false), h.deps);
    expect(out.status).toBe('no_slots');
    expect(h.sender.sent).toHaveLength(0);
    expect(h.store.rows).toHaveLength(0);
    expect(h.calendar.touched).toBe(0);
    expect(h.mailbox.calls).toBe(0);
  });

  it('slots plus a salary question: slots are offered and the acceptance has no pay text', async () => {
    const s = await seedThread(env);
    const h = makeHarness();
    h.mailbox.context = {
      ...h.mailbox.context,
      subject: 'Re: Interview and salary expectations',
    };
    const interviewId = await offerAndConfirm(s, h, 0, true);
    expect(h.sender.sent.filter((m) => m.kind === 'slot_confirmation')).toHaveLength(1);

    await book(s, h, interviewId);
    const reply = replies(h)[0]!;
    // The recruiter's subject quoted pay; the reply uses a neutral one and passes the whole guard.
    expect(reply.subject).toBe('Re: Interview for Staff Engineer');
    expect(reply.text).not.toMatch(MONEY_TEXT);
    expect(reply.html).not.toMatch(MONEY_TEXT);
    expect(await moneyGuard.check(reply)).toEqual({ ok: true });
    expect(h.store.rows.filter((r) => r.blocked)).toHaveLength(0);
  });

  it('a clean recruiter subject is kept on the reply', async () => {
    const s = await seedThread(env);
    const h = makeHarness();
    const interviewId = await offerAndConfirm(s, h);
    await book(s, h, interviewId);
    expect(replies(h)[0]!.subject).toBe('Re: Interview for Staff Engineer');
  });
});

describe('book-interview job', () => {
  const approve = async (t: Seeded['t']) => {
    await insertProfileVersion(t.handle, {
      userId: t.userId,
      document: profileDocumentSchema.parse(profile),
    });
    await setApprovedProfileVersion(t.handle, t.userId, 1);
  };

  it('books for an approved user through the guarded job', async () => {
    const s = await seedThread(env);
    await approve(s.t);
    const h = makeHarness();
    const interviewId = await offerAndConfirm(s, h);
    const out = await runBookInterview(
      env.db,
      { tenantId: s.t.id, userId: s.t.userId, interviewId },
      () => h.deps,
    );
    expect(out.ran).toBe(true);
    expect(out.result).toMatchObject({ status: 'booked' });
    expect(replies(h)).toHaveLength(1);
  });

  it('does not run for a user without an approved profile', async () => {
    const s = await seedThread(env);
    const h = makeHarness();
    const interviewId = await offerAndConfirm(s, h);
    const out = await runBookInterview(
      env.db,
      { tenantId: s.t.id, userId: s.t.userId, interviewId },
      () => h.deps,
    );
    expect(out.ran).toBe(false);
    expect(replies(h)).toHaveLength(0);
    expect(h.calendar.created).toHaveLength(0);
  });
});

describe('requeueUnbookedInterviews', () => {
  it('hands back confirmed interviews that are not booked, and stops once they are', async () => {
    const s = await seedThread(env);
    const h = makeHarness();
    const interviewId = await offerAndConfirm(s, h);
    const queued: string[] = [];
    const enqueue = async (d: { interviewId: string }) => {
      queued.push(d.interviewId);
    };
    expect(await requeueUnbookedInterviews(s.t.handle, s.t.userId, enqueue)).toBe(1);
    expect(queued).toEqual([interviewId]);
    await book(s, h, interviewId);
    expect(await requeueUnbookedInterviews(s.t.handle, s.t.userId, enqueue)).toBe(0);
  });
});
